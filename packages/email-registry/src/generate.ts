import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { build } from 'esbuild';
// Same email conventions as the preview: components/assets/tests are helpers.
async function discoverTemplates(directory: string): Promise<string[]> {
  const excluded = new Set(['node_modules', 'dist', 'build', 'components', 'assets', 'static', '__tests__', '__snapshots__']);
  const files: string[] = [];
  async function visit(path: string) {
    for (const entry of (await readdir(path, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
      if (/^[._]/.test(entry.name) || excluded.has(entry.name)) continue;
      const file = join(path, entry.name);
      if (entry.isDirectory()) await visit(file);
      else if (entry.isFile() && entry.name.endsWith('.tsx') && !/\.(test|spec|stories)\.tsx$/.test(entry.name)) files.push(file);
    }
  }
  await visit(directory);
  return files;
}

/** Writes static imports so TypeScript knows every email and its exact input type. */
export async function generateRegistry(directory: string, output: string): Promise<void> {
  directory = resolve(directory);
  output = resolve(output);
  if (!output.endsWith('.ts')) throw new Error('Registry output must be a .ts file');
  const files = await discoverTemplates(directory);
  const result = files.length ? await build({
    entryPoints: files, outdir: resolve(dirname(output), '.email-entries'),
    write: false, metafile: true, bundle: false, format: 'esm',
    jsx: 'automatic', jsxImportSource: 'preact', logLevel: 'silent',
  }) : undefined;
  const entries = new Set(Object.values(result?.metafile?.outputs ?? {})
    .filter(entry => entry.exports.includes('default'))
    .map(entry => resolve(entry.entryPoint!)));
  type Branch = Map<string, Branch | number>;
  const tree: Branch = new Map();
  const imports: string[] = [];
  for (const file of files.filter(file => entries.has(file))) {
    const id = imports.length;
    let path = relative(dirname(output), file).split(sep).join('/').replace(/\.tsx$/, '.js');
    if (!path.startsWith('.')) path = './' + path;
    imports.push(`import Email${id} from ${JSON.stringify(path)};`);
    const keys = relative(directory, file).split(sep).join('/').replace(/\.tsx$/, '').split('/').map(part =>
      part.replace(/[-_ ]+(\w)/g, (_, c: string) => c.toUpperCase()).replace(/^\w/, c => c.toLowerCase()));
    let branch = tree;
    for (const key of keys.slice(0, -1)) {
      const existing = branch.get(key);
      if (typeof existing === 'number') throw new Error(`Email/folder name collision: ${key}`);
      if (!existing) branch.set(key, new Map());
      branch = branch.get(key) as Branch;
    }
    const key = keys.at(-1)!;
    if (branch.has(key)) throw new Error(`Duplicate registry key: ${keys.join('.')}`);
    branch.set(key, id);
  }
  const render = (branch: Branch, depth = 1): string => '{\n' + [...branch].map(([key, value]) =>
    `${'  '.repeat(depth)}${JSON.stringify(key)}: ${typeof value === 'number' ? `createEmailRenderer(Email${value})` : render(value, depth + 1)},`
  ).join('\n') + '\n' + '  '.repeat(depth - 1) + '}';
  const source = `// Generated by preact-email-registry.\nimport { createEmailRenderer } from '@tallystone/preact-email-registry';\n${imports.join('\n')}\n\nexport const emails = ${render(tree)};\n`;
  // Leave the file untouched when only email contents change.
  if (await readFile(output, 'utf8').catch(() => '') === source) return;
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, source);
}
